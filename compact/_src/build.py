#!/usr/bin/env python3
"""Generates ../NN-name.test.ts = harness.ts + NN-name.body.ts. Run from anywhere."""
import glob, os
here = os.path.dirname(os.path.abspath(__file__))
out = os.path.dirname(here)
harness = open(os.path.join(here, 'harness.ts')).read()
for body in sorted(glob.glob(os.path.join(here, '*.body.ts'))):
    name = os.path.basename(body).replace('.body.ts', '.test.ts')
    src = open(body).read()
    header = '// GENERATED by _src/build.py from _src/harness.ts + _src/%s. Edit the sources, not this file.\n' % os.path.basename(body)
    open(os.path.join(out, name), 'w').write(header + harness + '\n// ---------------- tests ----------------\n' + src)
    print('wrote', name)
